#!/usr/bin/env bash
set -euo pipefail
umask 077
repo="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
work=$(mktemp -d "${TMPDIR:-/tmp}/codex-mcp-test.XXXXXX")
trap 'rm -rf "$work"' EXIT
export CODEX_HOME="$work/codex" CONFIG_PI_HOME="$work/pi"
mkdir -p "$CODEX_HOME" "$CONFIG_PI_HOME/agent"
printf 'model = "test-model"\n\n[projects."/fixture"]\ntrust_level = "trusted"\n' > "$CODEX_HOME/config.toml"
cp "$CODEX_HOME/config.toml" "$work/original"
printf '%s\n' '{"mcpServers":{"fixture":{"command":"printf","args":["hello\n","quote\""],"env":{"FAKE_TOKEN":"literal$VALUE\\tail"},"literalEnv":true,"directTools":false,"lifecycle":"lazy"}}}' > "$CONFIG_PI_HOME/agent/mcp.json"
if [[ -f "$repo/codex/import-mcp.sh" ]]; then bash "$repo/init.sh" --codex-mcp; fi
codex mcp get fixture --json > "$work/actual.json" 2>/dev/null
jq -e '.transport.command == "printf" and .transport.args == ["hello\n","quote\""] and .transport.env.FAKE_TOKEN == "literal$VALUE\\tail"' "$work/actual.json" >/dev/null
# Existing content is retained verbatim, not regenerated by a TOML serializer.
head -c "$(wc -c < "$work/original" | tr -d ' ')" "$CODEX_HOME/config.toml" > "$work/prefix"
cmp "$work/original" "$work/prefix"
cp "$CODEX_HOME/config.toml" "$work/once"
bash "$repo/init.sh" --codex-mcp
cmp "$work/once" "$CODEX_HOME/config.toml"
jq '.mcpServers.fixture.command="different"' "$CONFIG_PI_HOME/agent/mcp.json" > "$work/changed"
mv "$work/changed" "$CONFIG_PI_HOME/agent/mcp.json"
if bash "$repo/init.sh" --codex-mcp > "$work/conflict.log" 2>&1; then echo 'Expected conflict refusal' >&2; exit 1; fi
cmp "$work/once" "$CODEX_HOME/config.toml"
mv "$CODEX_HOME/config.toml" "$work/saved-config"
mkdir "$CODEX_HOME/config.toml"
printf 'keep\n' > "$CODEX_HOME/config.toml/sentinel"
if bash "$repo/init.sh" --codex-mcp > "$work/directory.log" 2>&1; then echo 'Expected non-file target refusal' >&2; exit 1; fi
test -f "$CODEX_HOME/config.toml/sentinel"
printf '%s\n' 'PASS: native Codex parsing, exact arguments/env, preserved settings, idempotence, conflict and non-file refusal'
